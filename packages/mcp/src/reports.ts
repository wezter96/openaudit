import { constants } from "node:fs";
import { lstat, mkdir, open, realpath, rename, rm } from "node:fs/promises";
import { join } from "node:path";
import {
	type AuditorResult,
	correlate,
	type Finding,
	type FindingInput,
	fingerprintOf,
	type Report,
	type Severity,
	severityRank,
	summarize,
	toJson,
} from "@openaudit/core";

/** A server-generated report id such as `20261013t005800-0123456789ab`. */
export type ReportId = string;
/** A path on the local filesystem. */
export type FilePath = string;
/** Formats a report is saved to disk in. */
export type ReportFormat = "json" | "html";

/** Report ids are generated by the server; anything else is rejected before touching disk. */
export const REPORT_ID_PATTERN = /^[a-z0-9-]{1,64}$/;
export const isReportId = (id: ReportId): boolean => REPORT_ID_PATTERN.test(id);

/** Outcome of saving a report next to its target. */
export type SaveResult =
	| { readonly saved: true; readonly path: FilePath }
	| { readonly saved: false; readonly reason: string };

/** In-memory LRU of recent reports, mirrored to `.openaudit/reports/` for directory targets. */
export class ReportStore {
	private readonly reports = new Map<ReportId, Report>();
	private readonly paths = new Map<ReportId, FilePath>();

	constructor(
		private readonly capacity = 20,
		private readonly writeToDisk = true,
	) {}

	/** Sortable, unguessable id: `20261013t005800-<12 random hex>`. */
	static newId(): ReportId {
		const time = new Date()
			.toISOString()
			.replace(/[-:]/g, "")
			.slice(0, 15)
			.toLowerCase();
		return `${time}-${crypto.randomUUID().replaceAll("-", "").slice(0, 12)}`;
	}

	get(id: ReportId): Report | undefined {
		const report = this.reports.get(id);
		if (report) {
			// refresh recency
			this.reports.delete(id);
			this.reports.set(id, report);
		}
		return report;
	}

	path(id: ReportId): FilePath | undefined {
		return this.paths.get(id);
	}

	ids(): ReadonlyArray<ReportId> {
		return [...this.reports.keys()].reverse();
	}

	/**
	 * Stores (or replaces) a report in memory and tries to save it under the
	 * target. Targets without a directory are kept in memory only.
	 */
	async put(id: ReportId, report: Report): Promise<SaveResult | undefined> {
		if (!isReportId(id)) throw new Error(`Invalid report id "${id}"`);
		this.reports.delete(id);
		this.reports.set(id, report);
		while (this.reports.size > this.capacity) {
			const oldest = this.reports.keys().next().value;
			if (oldest === undefined) break;
			this.reports.delete(oldest);
			this.paths.delete(oldest);
		}
		if (!this.writeToDisk || !reportsRoot(report)) return undefined;
		const result = await persist(id, report, "json", toJson(report));
		if (result.saved) this.paths.set(id, result.path);
		else this.paths.delete(id);
		return result;
	}
}

/** Target directory whose `.openaudit/reports/` receives reports, if any. */
const reportsRoot = (report: Report): FilePath | undefined =>
	report.target.type === "directory" ? report.target.root : undefined;

const isObject = (value: unknown): value is object =>
	typeof value === "object" && value !== null;

const errorCode = (error: unknown): string | undefined =>
	isObject(error) && "code" in error ? String(error.code) : undefined;

/** `.catch` handler for creating something that may already exist. */
const ignoreExists = (error: unknown): void => {
	if (errorCode(error) !== "EEXIST") throw error;
};

/** Creates `dir` if needed, then refuses it unless it is a real directory. */
const ensureRealDir = async (dir: FilePath): Promise<void> => {
	await mkdir(dir, { mode: 0o700 }).catch(ignoreExists);
	const stat = await lstat(dir);
	if (stat.isSymbolicLink())
		throw new Error(`${dir} is a symlink; refusing to write through it`);
	if (!stat.isDirectory()) throw new Error(`${dir} is not a directory`);
};

/**
 * `<root>/.openaudit/reports` as real directories. The target is untrusted:
 * it may ship `.openaudit` as a symlink to `~/.ssh`, so every component is
 * checked with lstat and the result must resolve inside the root.
 */
const reportsDirUnder = async (rootInput: FilePath): Promise<FilePath> => {
	const root = await realpath(rootInput);
	let dir = root;
	for (const part of [".openaudit", "reports"]) {
		dir = join(dir, part);
		await ensureRealDir(dir);
	}
	const real = await realpath(dir);
	if (real !== join(root, ".openaudit", "reports"))
		throw new Error(`${dir} resolves outside the target (${real})`);
	return real;
};

/** Creates a new file; fails if anything (including a symlink) already exists there. */
const writeNew = async (path: FilePath, content: string): Promise<void> => {
	const handle = await open(
		path,
		constants.O_WRONLY |
			constants.O_CREAT |
			constants.O_EXCL |
			(constants.O_NOFOLLOW ?? 0),
		0o600,
	);
	try {
		await handle.writeFile(content);
	} finally {
		await handle.close();
	}
};

/**
 * Saves `<root>/.openaudit/reports/<id>.<ext>` without following symlinks:
 * content goes to a fresh, exclusively created temp file that is renamed into
 * place (rename replaces a planted symlink instead of writing through it).
 * Also drops a `.gitignore` so reports stay out of git.
 */
export const persist = async (
	id: ReportId,
	report: Report,
	ext: ReportFormat,
	content: string,
): Promise<SaveResult> => {
	if (!isReportId(id))
		return { saved: false, reason: `invalid report id "${id}"` };
	const root = reportsRoot(report);
	if (!root) return { saved: false, reason: "the target is not a directory" };
	try {
		const dir = await reportsDirUnder(root);
		await writeNew(join(dir, "..", ".gitignore"), "*\n").catch(ignoreExists);
		const path = join(dir, `${id}.${ext}`);
		const temp = join(dir, `.${id}.${crypto.randomUUID()}.tmp`);
		await writeNew(temp, content);
		await rename(temp, path).catch(async (error) => {
			await rm(temp, { force: true });
			throw error;
		});
		return { saved: true, path };
	} catch (error) {
		return {
			saved: false,
			reason: error instanceof Error ? error.message : String(error),
		};
	}
};

/** One line for tool results: where the report went, or why it stayed in memory. */
export const saveNote = (result: SaveResult | undefined): string | undefined =>
	result === undefined
		? undefined
		: result.saved
			? `Saved: ${result.path}`
			: `Not saved to disk (kept in memory only): ${result.reason}`;

/** The `reportPath` / `notSaved` fields of a tool result that saved a report. */
export const saveFields = (result: SaveResult | undefined) => {
	const reportPath = result?.saved ? result.path : undefined;
	return {
		...(reportPath ? { reportPath } : {}),
		...(result && !result.saved ? { notSaved: result.reason } : {}),
	};
};

/** Findings that count, most severe first (duplicates left out). */
export const allFindingsOf = (report: Report): Finding[] =>
	report.results
		.flatMap((r) => r.findings)
		.filter((f) => f.duplicateOf === undefined)
		.sort((a, b) => severityRank(a.severity) - severityRank(b.severity));

export interface ReportDiff {
	readonly new: Finding[];
	readonly fixed: Finding[];
	readonly unchanged: Finding[];
	readonly scoreDelta: number;
}

/** Compares two reports by finding fingerprint. */
export const diffReports = (base: Report, head: Report): ReportDiff => {
	const before = new Map(allFindingsOf(base).map((f) => [f.fingerprint, f]));
	const after = new Map(allFindingsOf(head).map((f) => [f.fingerprint, f]));
	return {
		new: [...after.values()].filter((f) => !before.has(f.fingerprint)),
		fixed: [...before.values()].filter((f) => !after.has(f.fingerprint)),
		unchanged: [...after.values()].filter((f) => before.has(f.fingerprint)),
		scoreDelta: head.summary.score - base.summary.score,
	};
};

/** True when any finding is at least as severe as `threshold`. */
export const breaches = (report: Report, threshold: Severity): boolean =>
	allFindingsOf(report).some(
		(f) => severityRank(f.severity) <= severityRank(threshold),
	);

/** The auditor a playbook's submitted findings are filed under. */
export interface AgentAuditor {
	readonly id: string;
	readonly title: string;
	readonly categories: ReadonlyArray<
		Report["summary"]["categories"][number]["category"]
	>;
}

const bySeverity = (a: Finding, b: Finding) =>
	severityRank(a.severity) - severityRank(b.severity);

/** A submitted finding with its rule id under the auditor's namespace. */
const toAgentFinding = (
	auditor: AgentAuditor,
	input: FindingInput,
): Finding => {
	const ruleId = input.ruleId.startsWith(`${auditor.id}/`)
		? input.ruleId
		: `${auditor.id}/${input.ruleId}`;
	const withRule = { ...input, ruleId };
	return {
		...withRule,
		auditor: auditor.id,
		fingerprint: input.fingerprint ?? fingerprintOf(auditor.id, withRule),
	};
};

/** The auditor result for `findings`, keeping what an earlier submission recorded. */
const agentResult = (
	auditor: AgentAuditor,
	existing: AuditorResult | undefined,
	findings: Finding[],
): AuditorResult => ({
	auditor: auditor.id,
	title: existing?.title ?? auditor.title,
	engine: "agentic",
	categories: [
		...new Set([
			...(existing?.categories ?? auditor.categories),
			...findings.map((f) => f.category),
		]),
	],
	status: findings.some((f) => f.severity !== "info") ? "failed" : "passed",
	message: "Findings submitted by the host agent via MCP",
	durationMs: existing?.durationMs ?? 0,
	findings,
});

/**
 * Adds host-agent findings to a report as an `agentic` auditor result named
 * after the playbook. Findings with a known fingerprint are replaced, so
 * resubmitting is idempotent.
 */
export const mergeAgentFindings = (
	report: Report,
	auditor: AgentAuditor,
	inputs: ReadonlyArray<FindingInput>,
): { report: Report; added: Finding[] } => {
	const added = inputs.map((input) => toAgentFinding(auditor, input));
	const existing = report.results.find((r) => r.auditor === auditor.id);
	const byFingerprint = new Map(
		(existing?.findings ?? []).map((f) => [f.fingerprint, f]),
	);
	for (const f of added) byFingerprint.set(f.fingerprint, f);
	const findings = [...byFingerprint.values()].sort(bySeverity);
	const result = agentResult(auditor, existing, findings);
	const results = correlate(
		existing
			? report.results.map((r) => (r.auditor === auditor.id ? result : r))
			: [...report.results, result],
	);
	return {
		report: {
			...report,
			finishedAt: new Date().toISOString(),
			summary: summarize(results),
			results,
		},
		added,
	};
};
